import { todayIso } from "@museumsufer/core/date";
import { decodeEntities, stripHtml } from "@museumsufer/core/html";
import PQueue from "p-queue";
import { HALLE02_DETAIL_CACHE, type Halle02CacheEntry } from "../data/halle02-detail-cache";
import type { CanonicalScrapedEvent, ScrapedLabel, VenueScrapeResult } from "../types";

const BASE = "https://www.halle02.de";
const REST_URL = `${BASE}/wp-json/wp/v2/programm`;
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

const LAT = 49.3998;
const LON = 8.686;
const CITY = "heidelberg";

export interface WpProgram {
  id: number;
  slug: string;
  /** WP last-modified stamp; the committed detail cache is valid only while it matches. */
  modified: string;
  link: string;
  title: { rendered: string };
  /** WP taxonomy classes, e.g. `veranstaltungsart-live`, `genre-pop`. */
  class_list?: string[];
  excerpt?: { rendered: string };
  content?: { rendered: string };
  _embedded?: {
    "wp:featuredmedia"?: Array<{ source_url?: string }>;
  };
}

export interface ParsedDetail {
  title: string;
  description: string | null;
  date: string;
  time: string | null;
  endTime: string | null;
  priceMin: number | null;
  ticketUrl: string | null;
  venueRoom: string | null;
  imageUrl: string | null;
}

/** Pages of the REST listing to read (100 posts each, newest first). The listing
 *  is cheap; the expensive part is the per-post detail fetch, which the cache
 *  makes unnecessary for every post already seen. */
const LISTING_PAGES = 4;

/** Detail pages fetched live per run, for posts missing from the committed
 *  cache or modified since. A fixed count, never a wall-clock budget: the output
 *  must depend on upstream data only, not on how fast the server answered. Every
 *  live fetch is written back to the committed cache by event-hub's scrape.ts,
 *  so a backlog beyond this count shrinks by this many posts per run. */
const MAX_UNCACHED_DETAILS = 40;

/** The event date exists only on the rendered detail page (the REST payload
 *  carries a stub `content`, ~5 s per page). Posts whose slug already names a
 *  past date or month are skipped; an undated or same-/future-month slug is
 *  kept and date-checked after the detail is known. */
export function isUpcomingCandidate(slug: string, today: string): boolean {
  const slugDate = parseSlugDate(slug);
  if (slugDate && slugDate.date < today) return false;
  return !slugMonthBefore(slug, today);
}

let cacheSnapshot: Record<number, Halle02CacheEntry> | null = null;

/** The detail cache as the last completed scrape would commit it: entries still
 *  listed upstream (cached or freshly fetched). `null` until a scrape completes,
 *  so a failed run never prunes or rewrites the committed file. */
export function halle02CacheSnapshot(): Record<number, Halle02CacheEntry> | null {
  return cacheSnapshot;
}

/** Byte-stable module text for the committed cache: ids ascending, one JSON line each. */
export function serializeHalle02Cache(cache: Readonly<Record<number, Halle02CacheEntry>>): string {
  const ids = Object.keys(cache).map(Number).sort((a, b) => a - b);
  const body = ids.map((id) => `  ${id}: ${JSON.stringify(cache[id])},`).join("\n");
  return `// Auto-generated by event-hub scrape.ts / scripts/refresh-halle02-cache.ts — do not edit by hand.
import type { ParsedDetail } from "../venues/halle02";

export interface Halle02CacheEntry {
  /** WP \`modified\` stamp the detail was parsed at; a newer stamp invalidates the entry. */
  modified: string;
  detail: ParsedDetail | null;
}

export const HALLE02_DETAIL_CACHE: Readonly<Record<number, Halle02CacheEntry>> = {
${body}
};
`;
}

export async function scrapeHalle02(): Promise<VenueScrapeResult> {
  const today = todayIso();
  const posts = await fetchProgramList();
  const candidates = posts.filter((post) => isUpcomingCandidate(post.slug, today));

  const details = new Map<number, ParsedDetail | null>();
  const next: Record<number, Halle02CacheEntry> = {};
  const uncached: WpProgram[] = [];
  for (const post of candidates) {
    const hit = HALLE02_DETAIL_CACHE[post.id];
    if (hit && hit.modified === post.modified) {
      details.set(post.id, hit.detail);
      next[post.id] = hit;
    } else uncached.push(post);
  }

  const live = uncached.sort((a, b) => b.id - a.id).slice(0, MAX_UNCACHED_DETAILS);
  if (uncached.length > live.length) {
    console.warn(`halle02: ${uncached.length - live.length} uncached posts beyond the live cap; they fill in over the next runs`);
  }
  const queue = new PQueue({ concurrency: 8 });
  let failed = 0;
  await Promise.all(
    live.map((post) =>
      queue.add(async () => {
        try {
          const detail = await fetchDetail(post);
          details.set(post.id, detail);
          next[post.id] = { modified: post.modified, detail };
        } catch {
          failed++;
          // A flaky refetch must not drop a post we already know: keep its stale detail.
          const stale = HALLE02_DETAIL_CACHE[post.id];
          if (stale) {
            details.set(post.id, stale.detail);
            next[post.id] = stale;
          }
        }
      }),
    ),
  );
  if (live.length > 0 && failed > live.length / 2) {
    throw new Error(`halle02: ${failed}/${live.length} live detail fetches failed`);
  }
  cacheSnapshot = next;

  const detailResults = candidates.map((post) => {
    const parsed = details.get(post.id);
    return parsed && parsed.date >= today ? { post, parsed } : null;
  });

  const events: CanonicalScrapedEvent[] = [];
  for (const result of detailResults) {
    if (!result) continue;
    const { post, parsed } = result;
    const labels = halle02Labels(parsed.title, parsed.description, post.class_list ?? []);

    events.push({
      source_event_id: String(post.id),
      title: parsed.title,
      subtitle: parsed.description,
      description: parsed.description,
      date: parsed.date,
      time: parsed.time,
      end_time: parsed.endTime,
      detail_url: post.link,
      ticket_url: parsed.ticketUrl ?? post.link,
      image_url: parsed.imageUrl,
      price_min: parsed.priceMin,
      venue_room: parsed.venueRoom,
      city: CITY,
      lat: LAT,
      lon: LON,
      labels,
    });
  }

  events.sort(
    (a, b) =>
      a.date.localeCompare(b.date) ||
      (a.time ?? "").localeCompare(b.time ?? "") ||
      a.source_event_id.localeCompare(b.source_event_id),
  );

  return { source_slug: "halle02", display_name: "halle02", events };
}

const CLUB_KINDS = ["party", "szene", "ersti", "noir", "sundowner", "daytime", "food-drinks", "open-air", "kulturpass"];

/**
 * halle02 is a club and live venue, not a concert hall: the WP taxonomy
 * (`veranstaltungsart-*`, `genre-*`) says what each programme item is, so the
 * labels come from it. Only `live` items with a jazz/classical/world/choral
 * genre become konzert-haus genres; club nights and rock/pop shows get the
 * non-genre `music:electronic|rock|pop` labels the concert app ignores.
 */
function halle02Labels(title: string, description: string | null, classes: readonly string[]): ScrapedLabel[] {
  const classifier = "upstream-tag" as const;
  const confidence = 0.8;
  const kinds = new Set(classes.filter((c) => c.startsWith("veranstaltungsart-")).map((c) => c.slice(18)));
  const genres = new Set(classes.filter((c) => c.startsWith("genre-")).map((c) => c.slice(6)));
  const has = (...g: string[]) => g.some((x) => genres.has(x));
  const label = (l: string, c = confidence): ScrapedLabel => ({ label: l, confidence: c, classifier });

  if (looksLikeNonProgramme(title) || kinds.has("messen-maerkte-ausstellungen") || kinds.has("public-viewing")) {
    return [label("event:venue", 0.5)];
  }

  const labels: ScrapedLabel[] = [];
  const isClub = CLUB_KINDS.some((k) => kinds.has(k)) && !kinds.has("live");
  if (kinds.has("kleinkunst")) labels.push(label("stage:theater"));
  if (kinds.has("lesung-vortrag")) labels.push(label("talk:lesung"));
  if (kinds.has("workshop")) labels.push(label("talk:workshop", 0.7));
  if (kinds.has("tanz")) labels.push(label("dance:world"));
  if (kinds.has("kinder-eltern") && !kinds.has("party")) labels.push(label("museum:familie", 0.75));

  if (kinds.has("kleinkunst") || kinds.has("lesung-vortrag") || kinds.has("workshop") || kinds.has("tanz")) {
    return labels;
  }
  if (has("rock-haerter")) labels.push(label("music:rock"));
  else if (has("elektronisch", "techno-house", "edm", "drumnbass", "hardstyle")) labels.push(label("music:electronic"));
  else if (!isClub && has("jazz-klassik", "chor", "a-cappella")) {
    labels.push(label(`music:${classifyMusic(title, null, description, has("chor", "a-cappella") ? "classical" : "jazz")}`));
  } else if (!isClub && has("world-music", "folk") && !has("pop", "indie")) labels.push(label("music:world"));
  else if (has("pop", "indie", "hiphop", "reggaeton-dancehall", "funk-disco", "mixed-music", "world-music", "folk")) {
    labels.push(label("music:pop"));
  }
  if (labels.length === 0) labels.push(label("event:venue", 0.5));
  return labels;
}

export async function fetchProgramList(): Promise<WpProgram[]> {
  const posts: WpProgram[] = [];
  for (let page = 1; page <= LISTING_PAGES; page++) {
    const url = `${REST_URL}?per_page=100&orderby=date&order=desc&_embed&page=${page}`;
    const res = await fetch(url, { headers: { "User-Agent": UA, Accept: "application/json" } });
    if (!res.ok) break;
    const body = (await res.json()) as WpProgram[];
    if (!Array.isArray(body) || body.length === 0) break;
    posts.push(...body);
    if (body.length < 100) break;
  }
  return posts;
}

function parseSlugDate(slug: string): { date: string } | null {
  const numeric6 = /-(\d{2})(\d{2})(\d{2})$/.exec(slug);
  if (numeric6) {
    const year = 2000 + parseInt(numeric6[1], 10);
    const month = parseInt(numeric6[2], 10);
    const day = parseInt(numeric6[3], 10);
    if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      return { date: `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}` };
    }
  }
  return null;
}

const SLUG_MONTHS: Record<string, number> = {
  jan: 1,
  feb: 2,
  maerz: 3,
  mar: 3,
  apr: 4,
  mai: 5,
  juni: 6,
  jun: 6,
  juli: 7,
  jul: 7,
  aug: 8,
  sept: 9,
  sep: 9,
  okt: 10,
  nov: 11,
  dez: 12,
};
const SLUG_MONTH_RE = /-(jan|feb|maerz|mar|apr|mai|juni|jun|juli|jul|aug|sept|sep|okt|nov|dez)-?(\d{2})(?:$|-)/i;

/** Many halle02 slugs end in a German month-code (`…-mai26`, `…-nov25`). When
 *  that code names a month strictly before the current one the event is already
 *  past, so its detail fetch can be skipped. Undated or same-/future-month slugs
 *  return false and are fetched + date-checked as before, so the coarse code can
 *  never drop an upcoming event. */
function slugMonthBefore(slug: string, todayIso: string): boolean {
  const m = SLUG_MONTH_RE.exec(slug);
  if (!m) return false;
  const month = SLUG_MONTHS[m[1].toLowerCase()];
  if (!month) return false;
  const ym = `${2000 + parseInt(m[2], 10)}-${String(month).padStart(2, "0")}`;
  return ym < todayIso.slice(0, 7);
}

/** One detail page, parsed. `null` = the page has no usable title or date, which
 *  the cache records too so such posts are not refetched every run. */
export async function fetchDetail(post: WpProgram): Promise<ParsedDetail | null> {
  const r = await fetch(post.link, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(20_000) });
  if (!r.ok) throw new Error(`halle02 detail ${r.status} ${post.link}`);
  return parseDetail(await r.text(), post);
}

function parseDetail(html: string, post: WpProgram): ParsedDetail | null {
  const relevant = html.split("Das könnte dir auch gefallen")[0] ?? html;

  const h1Marker = '<h1 class="elementor-heading-title elementor-size-default">';
  const h1Index = relevant.indexOf(h1Marker);
  if (h1Index < 0) return null;

  const title = cleanText(
    extractFirst(
      relevant.slice(h1Index),
      /<h1[^>]*class="[^"]*elementor-heading-title[^"]*elementor-size-default[^"]*"[^>]*>([\s\S]*?)<\/h1>/i,
    ),
  );
  if (!title) return null;

  const description = buildDescription(post);
  const date = parseLastDateBefore(relevant, h1Index);
  if (!date) return null;

  const afterH1 = relevant.slice(h1Index);
  const time =
    parseTime(afterH1, /Beginn:\s*(\d{1,2}):(\d{2})/i) ?? parseTime(afterH1, /Einlass:\s*(\d{1,2}):(\d{2})/i);
  const endTime = parseTime(afterH1, /Ende:\s*(\d{1,2}):(\d{2})/i);

  const priceMin = parsePrice(relevant);
  const ticketUrl = extractFirst(relevant, /https?:\/\/t\.rausgegangen\.de\/tickets\/[^"'\s]+/i) ?? null;

  const venueRoom = extractCategory(relevant, "location") ?? null;
  const imageUrl =
    post._embedded?.["wp:featuredmedia"]?.[0]?.source_url ??
    extractFirst(relevant, /<meta[^>]+property="og:image"[^>]+content="([^"]+)"/i) ??
    null;

  return {
    title,
    description,
    date,
    time,
    endTime,
    priceMin,
    ticketUrl,
    venueRoom,
    imageUrl,
  };
}

function buildDescription(post: WpProgram): string | null {
  const raw = post.excerpt?.rendered || post.content?.rendered || "";
  const text = stripHtml(decodeEntities(raw)).replace(/\s+/g, " ").trim();
  if (!text) return null;
  return text.length > 400 ? `${text.slice(0, 397)}...` : text;
}

function parseLastDateBefore(text: string, index: number): string | null {
  const before = text.slice(0, index);
  const re = /\b(\d{1,2})\.(\d{1,2})\.(\d{2,4})\b/g;
  let last: { day: number; month: number; year: number } | null = null;
  for (const m of before.matchAll(re)) {
    const day = parseInt(m[1], 10);
    const month = parseInt(m[2], 10);
    let year = parseInt(m[3], 10);
    if (year < 100) year += 2000;
    if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      last = { day, month, year };
    }
  }
  if (!last) return null;
  return `${last.year}-${String(last.month).padStart(2, "0")}-${String(last.day).padStart(2, "0")}`;
}

function parseTime(text: string, re: RegExp): string | null {
  const m = re.exec(text);
  if (!m) return null;
  return `${String(parseInt(m[1], 10)).padStart(2, "0")}:${m[2]}`;
}

function parsePrice(text: string): number | null {
  if (/eintritt\s*frei|kostenlos|gratis/i.test(text)) return null;
  const m = /ab\s+(\d+)(?:[,.](\d{2}))?\s*€/.exec(text);
  if (!m) return null;
  const euros = parseInt(m[1], 10);
  const cents = m[2] ? parseInt(m[2], 10) : 0;
  return euros + cents / 100;
}

function extractCategory(text: string, taxonomy: string): string | null {
  const re = new RegExp(`href="https://www\\.halle02\\.de/${taxonomy}/[^"]+/">([^<]+)</a>`, "gi");
  const out: string[] = [];
  for (const m of text.matchAll(re)) {
    const t = cleanText(m[1]);
    if (t) out.push(t);
  }
  return out.length ? out.join(" ") : null;
}

function extractFirst(text: string, re: RegExp): string | null {
  const m = re.exec(text);
  return m ? cleanText(m[1]) : null;
}

function cleanText(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const text = stripHtml(decodeEntities(raw)).replace(/\s+/g, " ").trim();
  return text || null;
}
